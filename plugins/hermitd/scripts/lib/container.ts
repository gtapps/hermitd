// Container detection, shared by the booter and doctor so neither has to import
// the other.

import fs from 'node:fs';
import path from 'node:path';

/** Root-owned managed-settings drop-in the generated Docker image bakes. */
export const MANAGED_SECURITY_SETTINGS = '/etc/claude-code/managed-settings.d/hermitd-security.json';

/** Whether the project's image bakes the managed deny floor: only a renderer-generated
 *  Dockerfile does, and `docker.security.managed_ceiling: false` opts out. */
export function managedFloorApplies(projectRoot: string, config: any): boolean {
  if (config?.docker?.security?.managed_ceiling === false) return false;
  try { return fs.readFileSync(path.join(projectRoot, 'Dockerfile.hermit'), 'utf8').startsWith('# Generated by hermitd '); }
  catch { return false; }
}

/** Detect if running inside a container (Docker, Podman, LXC). */
export function isContainer(): boolean {
  return (
    fs.existsSync('/.dockerenv') ||
    fs.existsSync('/run/.containerenv') ||
    process.env.container === 'docker'
  );
}
