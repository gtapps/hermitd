test('another check waits briefly for the active approval lock', async () => {
  const f = fixture();
  await f.approve();
  f.write('docker-compose.override.yml', 'services: {}\n');
  const { promise, resolve } = Promise.withResolvers<string>();
  const first = f.approve(() => promise);
  try {
    const script = path.resolve(import.meta.dir, '../scripts/lib/approval.ts');
    const code = `import { approveProject } from ${JSON.stringify(script)};
      process.exitCode = (await approveProject(process.argv[1], {configRoot: process.argv[2], waitMs: 60})).code;`;
    const child = Bun.spawn([process.execPath, '-e', code, f.project, f.configRoot], { stdout: 'pipe', stderr: 'pipe' });
    expect(await new Response(child.stdout).text()).toContain('Another Docker lifecycle command or hermitd approve');
    expect(await child.exited).toBe(1);
  } finally {
    resolve('n');
    await first;
  }
});

