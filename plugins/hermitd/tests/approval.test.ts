import { afterAll, describe, expect, test } from 'bun:test';
import fs from 'node:fs';
import path from 'node:path';
import { appliedSet, approvalStore, approveProject, contextsName, markApprovalNote, unannouncedCandidate } from '../scripts/lib/approval';
import { freshDirFactory } from './helpers/workdir';

const { freshDir, cleanup } = freshDirFactory('hermit-approval-');
afterAll(cleanup);

function fixture(generated = false) {
  const root = freshDir();
  const project = path.join(root, 'project');
  const configRoot = path.join(root, 'claude');
  fs.mkdirSync(path.join(project, '.hermit'), { recursive: true });
  const write = (name: string, value: string) => fs.writeFileSync(path.join(project, name), value);
  write('.hermit/config.json', JSON.stringify(generated ? { channels: {}, docker: { packages: [] } } : {}));
  write('docker-compose.hermit.yml', 'services: {}\n');
  write('Dockerfile.hermit', generated ? '# Generated by hermitd 0.0.1\nstale\n' : 'FROM scratch\n');
  write('docker-entrypoint.hermit.sh', 'entrypoint\n');
  const messages: string[] = [];
  const approve = (prompt?: () => string | Promise<string>) => approveProject(project, {
    configRoot, prompt, report: message => messages.push(message),
  });
  return { project, configRoot, store: approvalStore(project, configRoot), write, approve, messages };
}

test('first approval records a private frozen baseline without a terminal or Docker config', async () => {
  const f = fixture();
  const result = await f.approve();
  expect(result.code).toBe(0);
  const applied = result.applied!;
  expect(appliedSet(f.project, f.configRoot)).toBe(applied);
  expect(f.messages).toHaveLength(1);
  expect(f.messages[0]).toContain('Recorded Docker approval baseline');
  expect(f.messages[0]).toContain('docker-compose.hermit.yml');
  expect(fs.readFileSync(path.join(applied, 'Dockerfile.hermit'), 'utf8')).toBe('FROM scratch\n');
  expect(fs.readFileSync(path.join(applied, '.env'), 'utf8')).toBe('');
  expect(fs.statSync(f.store).mode & 0o777).toBe(0o700);
  for (const name of ['.env', 'Dockerfile.hermit', contextsName]) {
    expect(fs.statSync(path.join(applied, name)).mode & 0o777).toBe(0o600);
  }
  expect(fs.statSync(path.join(f.store, 'record.json')).mode & 0o777).toBe(0o600);
  expect(fs.readdirSync(f.project, { recursive: true })).not.toContain('record.json');
});

test('without a terminal a changed file is named and the applied set stays unchanged', async () => {
  const f = fixture();
  const first = (await f.approve()).applied!;
  const record = path.join(f.store, 'record.json');
  const before = fs.readFileSync(record);
  f.write('docker-compose.override.yml', 'services: {hermit: {privileged: true}}\n');
  f.messages.length = 0;
  expect(await f.approve()).toEqual({ code: 1 });
  expect(f.messages.join('\n')).toContain('docker-compose.override.yml');
  expect(f.messages.join('\n')).toContain('Run hermitd approve in a terminal');
  f.messages.length = 0;
  expect(await f.approve(() => 'n')).toEqual({ code: 1 });
  expect(f.messages.join('\n')).toContain('+services:');
  expect(f.messages.at(-1)).toContain(first);
  expect(appliedSet(f.project, f.configRoot)).toBe(first);
  expect(fs.readFileSync(record)).toEqual(before);
  expect(fs.existsSync(path.join(first, 'docker-compose.override.yml'))).toBe(false);
  expect(fs.readdirSync(f.store).sort()).toEqual([path.basename(record), path.basename(first)].sort());
});

test('terminal approval freezes the reviewed bytes and the next unchanged invocation is quiet', async () => {
  const f = fixture();
  await f.approve();
  const override = 'services: {hermit: {ports: ["3131:3131"]}}\n';
  f.write('docker-compose.override.yml', override);
  const result = await f.approve(() => {
    f.write('docker-compose.override.yml', 'services: {}\n');
    return 'y';
  });
  expect(fs.readFileSync(path.join(result.applied!, 'docker-compose.override.yml'), 'utf8')).toBe(override);
  f.write('docker-compose.override.yml', override);
  f.messages.length = 0;
  expect(await f.approve()).toEqual(result);
  expect(f.messages).toEqual([]);
});

