test('both interpolation forms and variables in the base file are tracked without exposing dotenv values', async () => {
  const f = fixture(true);
  f.write('docker-compose.override.yml', 'services:\n  hermit:\n    environment: [A=${TOP:-}, B=$OTHER]\n');
  f.write('.env', 'TOP=before-one\nOTHER=before-two\nUNRELATED=old\nHERMIT_GH_TOKEN=old-secret\n');
  await f.approve();
  f.messages.length = 0;
  f.write('.env', 'TOP=before-one\nOTHER=before-two\nUNRELATED=new\nHERMIT_GH_TOKEN=new-secret\n');
  expect((await f.approve()).code).toBe(0);
  expect(f.messages).toEqual([]);
  f.write('.env', 'TOP=after-one\nOTHER=after-two\nUID=4242\nUNRELATED=new\nHERMIT_GH_TOKEN=new-secret\n');
  expect((await f.approve(() => 'y')).code).toBe(0);
  expect(f.messages).toEqual(['.env OTHER changed', '.env TOP changed', '.env UID changed']);
});

